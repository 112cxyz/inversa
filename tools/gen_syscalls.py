#!/usr/bin/env python3
"""The arm64 Linux (asm-generic) syscall numbers as an enum and a name table, from a sysroot's unistd.h.
  gen_syscalls.py build/sysroot > kernel/syscall_names.h"""
import re, sys
src = open(sys.argv[1] + "/usr/include/asm-generic/unistd.h").read()
nums = {}
for name, val in re.findall(r"#define (__NR3264_\w+|__NR_\w+)\s+(\S+)", src):
    nums[name] = val
def value(v, depth=0):
    if v.isdigit(): return int(v)
    return value(nums[v], depth + 1) if v in nums and depth < 8 else None
out = {}
for name, val in nums.items():
    if not name.startswith("__NR_") or name in ("__NR_syscalls", "__NR_arch_specific_syscall"): continue
    n = value(val)
    if n is not None and n < 1024: out.setdefault(n, name[5:])
print("// generated by tools/gen_syscalls.py from asm-generic/unistd.h: the arm64 Linux syscall numbers")
print("enum linux_syscall {")
for n in sorted(out): print("    NR_%s = %d," % (out[n], n))
print("};")
print()
print("static const char *const linux_syscall_names[%d] = {" % (max(out) + 1))
for n in sorted(out): print('    [%d] = "%s",' % (n, out[n]))
print("};")
